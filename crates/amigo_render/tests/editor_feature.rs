//! The egui integration and the shared amigo theme exist only with the
//! `editor` feature (amigo-theme AC-01, AC-12): a default build of the
//! renderer has no `egui` and no `theme` module.

use std::fs;
use std::path::Path;

fn manifest_file(path: &str) -> String {
    fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join(path))
        .unwrap_or_else(|e| panic!("{path} is readable: {e}"))
}

#[test]
fn the_theme_modules_are_behind_the_editor_feature() {
    let lib = manifest_file("src/lib.rs");
    let lines: Vec<&str> = lib.lines().map(str::trim).collect();
    for module in ["egui_integration", "egui_theme", "theme"] {
        let declaration = format!("pub mod {module};");
        let at = lines
            .iter()
            .position(|line| *line == declaration)
            .unwrap_or_else(|| panic!("lib.rs declares `{declaration}`"));
        assert_eq!(
            lines[at - 1],
            "#[cfg(feature = \"editor\")]",
            "`{declaration}` is gated behind the editor feature"
        );
    }
}

#[test]
fn egui_is_an_optional_dependency_of_the_editor_feature() {
    let manifest = manifest_file("Cargo.toml");
    let egui_lines: Vec<&str> = manifest
        .lines()
        .filter(|line| line.starts_with("egui"))
        .collect();
    assert_eq!(egui_lines.len(), 3, "egui, egui-wgpu, egui-winit");
    for line in egui_lines {
        assert!(line.contains("optional = true"), "{line}");
    }
    assert!(manifest.contains("default = []"));
    assert!(
        manifest.contains("editor = [\"dep:egui\", \"dep:egui-wgpu\", \"dep:egui-winit\"]"),
        "only the editor feature turns egui on"
    );
}

/// The generated module is committed as the generator wrote it: its header
/// names the generator, and CI's `theme` job regenerates and compares it.
#[test]
fn the_theme_module_is_the_generated_one() {
    let theme = manifest_file("src/theme.rs");
    assert!(
        theme.starts_with("// Generated by amigo-labs/website scripts/theme.ts — do not edit.\n")
    );
    assert!(theme.contains("pub const DARK: Palette"));
    assert!(theme.contains("pub const LIGHT: Palette"));
}
